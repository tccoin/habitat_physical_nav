"""The recording parameters of a ``generate_pose2d_dataset.py`` corpus, written
into the metadata at generation time and read back by every consumer.

------------------------------------------------------------------------
Why this module exists
------------------------------------------------------------------------
The rate a corpus was recorded at used to live nowhere except in the head of
whoever launched ``batch_gen.bash``. Every consumer carried its own
``--native-fps`` default instead, and those defaults drifted out of agreement
with reality: the shipped corpus was recorded at 30 Hz while both build
scripts defaulted to ``20.0``, silently understating every derived velocity by
exactly 1.5x. Nothing crashed -- a wrong ``native_fps`` is self-consistent all
the way down (chunk timing and replay ``dt`` are wrong *together*) -- and it
was only caught by forensics on a physics-aliasing artifact that happened to
stamp the physics-step count into the per-tick displacements.

That artifact is gone as of the move to 25 Hz (``dt = 0.04s`` is exactly 5 of
habitat's fixed 0.008 s Bullet steps, so there is one clean displacement mode
instead of two), which means the fingerprint that let us recover the true rate
after the fact is gone too. The rate has to be recorded, or the next wrong
assumption is undetectable.

So: anything a consumer would otherwise *assume* about how the data was
recorded is written into every metadata record, under the ``"recording"`` key.
That is the timing (``native_fps``, ``dt_native``, the physics timestep it
does or doesn't divide), the velocity caps that were actually in force while
driving, and enough provenance (render size, goal threshold, URDF, code
commit) to tell two corpora apart.

------------------------------------------------------------------------
Where it is written
------------------------------------------------------------------------
Into **every JSONL record**, not a sidecar file:

* the metadata is sharded per scene and generated by ~24 concurrent processes
  sharing one ``--output-dir``, so a single shared sidecar would be a
  write-contention hazard for no benefit;
* shards get copied, concatenated and subsetted by hand, and a record that
  carries its own parameters survives all of that;
* generation is resumable and *appends* to an existing shard, so a shard can
  physically contain records from two runs. Per-record parameters make that
  detectable (and :func:`resolve_corpus_params` /
  :func:`check_record_consistency` do detect it) instead of silently mixing
  two time bases in one file.

The cost is ~250 bytes per episode against a ``pose2d``/``rgb_paths`` payload
of hundreds of frames, i.e. nothing.

------------------------------------------------------------------------
Reading it back: the three cases a consumer must handle
------------------------------------------------------------------------
:func:`resolve_corpus_params` implements exactly one policy, shared by every
consumer, so no script gets to invent its own:

1. **The corpus records its parameters** (``schema_version >= 1``): they are
   returned as-is. The consumer needs no flag and gets true values. If the
   caller *also* passed an explicit ``--native-fps`` that disagrees with what
   is recorded, that is an error, not an override -- it is far more likely to
   be a stale habit from the pre-schema era than a deliberate reinterpretation.
2. **The corpus does not** (pre-schema shards, no ``"recording"`` key). There
   is no guessing: the resolve fails loudly with instructions unless the
   caller passes an explicit rate. Every pre-schema corpus in this repo was
   recorded at **30 Hz** (:data:`LEGACY_NATIVE_FPS`) -- off-grid, with the
   24% per-tick velocity ripple described in ``sim.py::step`` -- so the thing
   to pass is ``--native-fps 30``.
3. **The corpus disagrees with itself** (some shards/records carry parameters
   and others don't, or two records disagree on the timing): always an error.
   This is the resumed-across-the-fps-change case and it must never be
   averaged over.

``schema_version`` is what makes case 1 and case 2 distinguishable, and is
what the next person reads to tell which generation wrote a given file.
"""

import functools
import json
import math
import subprocess
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

# ---------------------------------------------------------------------------
# Schema
# ---------------------------------------------------------------------------
#: Bumped whenever the meaning of an existing field changes or a field a
#: consumer relies on is added. Absent (treated as 0) means "written before
#: the schema existed" -- see LEGACY_NATIVE_FPS.
#:
#: 1 -- first version. native_fps/dt_native/physics timing, effective velocity
#:      caps, render size, goal threshold, URDF, generator + code commit.
SCHEMA_VERSION = 1

#: Top-level key the parameter block lives under in each JSONL record.
RECORDING_KEY = "recording"

#: The rate every pre-schema corpus in this repo was recorded at. This is a
#: measured fact, not a guess: recovered from the corpus itself by the
#: physics-aliasing forensics in dump/upstream_bugfix/FINDINGS.md (predicted
#: 5:1 ratio of 0.064/0.080 m saturated increments at 1/30, measured 5.08:1
#: over 150 episodes / 104,362 ticks; 20 Hz and 25 Hz are both excluded with
#: zero occurrences of their signature increments). It is offered only as an
#: opt-in, never as a default.
LEGACY_NATIVE_FPS = 30.0

#: Habitat's fixed Bullet timestep in this stack. Probed live at generation
#: time (see :func:`probe_physics_timestep`); this is only the fallback when
#: no simulator is at hand.
DEFAULT_PHYSICS_TIMESTEP = 0.008

#: Linear velocity cap in force while recording, in m/s. Mirrors the ``v_max``
#: of the default ``HolonomicControllerConfig`` built inline by
#: ``controllers.HolonomicRobotController.__init__`` -- which is not exposed as
#: a module constant, so it cannot be imported. Guarded against drift by
#: ``tests/test_recording_metadata.py::test_mirrored_controller_limits_still_match_source``.
DEFAULT_V_MAX_MPS = 2.0

#: Angular velocity cap in force while recording, in rad/s. Both replay phases
#: land on the same number: move phases pass ``max_vw=2.0`` explicitly to
#: ``HolonomicRobotController.step`` (``replay.record_segmented_demo``), which
#: binds long before the config's inert ``w_max=70``; look phases are capped by
#: ``HeadingRotationConfig.w_max``, read live below. Mirrored for the same
#: reason as DEFAULT_V_MAX_MPS and guarded by the same test.
REPLAY_MOVE_MAX_VW_RADPS = 2.0

#: Fields that describe the *physics* of the recording and therefore must be
#: identical across every record of a corpus. Provenance fields (commit,
#: generator, render size) are deliberately excluded: a resumed run on a newer
#: commit is fine, a resumed run at a different tick rate is not.
CONSISTENCY_KEYS: Tuple[str, ...] = (
    "native_fps",
    "dt_native",
    "physics_timestep",
    "v_max_mps",
    "w_max_radps",
)

_FLOAT_TOL = 1e-9


class RecordingParamsError(RuntimeError):
    """Base class for every failure to establish a corpus's recording parameters."""


class MissingRecordingParams(RecordingParamsError):
    """The corpus predates the schema and the caller supplied no explicit rate."""


class InconsistentRecordingParams(RecordingParamsError):
    """Records within one corpus disagree about how they were recorded."""


@dataclass(frozen=True)
class RecordingParams:
    """How one corpus was recorded. Written to every metadata record.

    Timing:
        native_fps: control/render tick rate, Hz. One ``pose2d`` entry and one
            ``rgb_paths`` entry per tick.
        dt_native: ``1 / native_fps``, seconds. Stored explicitly rather than
            re-derived so a consumer never has to round-trip through the rate.
        physics_timestep: habitat's fixed Bullet step, seconds, as probed from
            the live simulator that produced the data.
        physics_steps_per_tick: ``dt_native / physics_timestep``.
        on_physics_grid: whether that ratio is a whole number. When it is
            False the recording carries the per-tick velocity ripple described
            in ``sim.py::step`` and derived velocities are only correct in the
            mean -- a consumer computing instantaneous speed should know.

    Limits actually in force while driving:
        v_max_mps / w_max_radps: the caps a saturated tick hits. Recorded
            because "what is the top speed in this data" is otherwise
            answerable only by reading three files, and has been answered
            wrongly twice (1.28/73 and 1.92/110 were both ``0.064/dt`` for a
            wrong ``dt``, i.e. artifacts of the ripple's lower mode).

    Provenance (not consistency-checked):
        image_width / image_height / image_ext: what the frames on disk are.
        goal_threshold_m: the final-pose filter every kept episode passed.
        urdf: robot description used.
        generator: script that wrote the corpus.
        code_commit: short git hash of this repo at generation time, or None.
    """

    native_fps: float
    dt_native: float
    physics_timestep: float
    physics_steps_per_tick: float
    on_physics_grid: bool
    v_max_mps: float
    w_max_radps: float
    image_width: Optional[int] = None
    image_height: Optional[int] = None
    image_ext: Optional[str] = None
    goal_threshold_m: Optional[float] = None
    urdf: Optional[str] = None
    generator: Optional[str] = None
    code_commit: Optional[str] = None
    schema_version: int = SCHEMA_VERSION
    #: Free-text marker set only for params the caller *assumed* rather than
    #: read (see :func:`legacy_params`). Never written by the generator.
    assumed_note: Optional[str] = None

    def as_dict(self) -> Dict[str, Any]:
        """JSON-ready dict, with ``None``-valued optional fields dropped."""
        return {k: v for k, v in asdict(self).items() if v is not None}

    @classmethod
    def from_dict(cls, blob: Dict[str, Any]) -> "RecordingParams":
        known = {f for f in cls.__dataclass_fields__}  # tolerate newer writers
        return cls(**{k: v for k, v in blob.items() if k in known})

    def consistency_view(self) -> Dict[str, float]:
        return {k: getattr(self, k) for k in CONSISTENCY_KEYS}

    def agrees_with(self, other: "RecordingParams") -> bool:
        for key in CONSISTENCY_KEYS:
            a, b = getattr(self, key), getattr(other, key)
            if a is None or b is None:
                if a is not b:
                    return False
            elif abs(float(a) - float(b)) > _FLOAT_TOL:
                return False
        return True

    def describe(self) -> str:
        grid = "on-grid" if self.on_physics_grid else "OFF-GRID (velocity ripple)"
        return (
            f"schema_version={self.schema_version} native_fps={self.native_fps:g} "
            f"dt_native={self.dt_native:.6g}s physics_timestep={self.physics_timestep:g}s "
            f"({self.physics_steps_per_tick:g} steps/tick, {grid}) "
            f"v_max={self.v_max_mps:g}m/s w_max={self.w_max_radps:g}rad/s"
            + (f" [{self.assumed_note}]" if self.assumed_note else "")
        )


# ---------------------------------------------------------------------------
# Building the block at generation time
# ---------------------------------------------------------------------------
def probe_physics_timestep(robot_sim: Any = None) -> float:
    """Habitat's fixed physics timestep, asked of the live simulator.

    Falls back to :data:`DEFAULT_PHYSICS_TIMESTEP` when there is no simulator
    to ask (unit tests, dry runs) or the call fails.
    """
    try:
        return float(robot_sim.sim.get_physics_time_step())
    except Exception:
        return float(DEFAULT_PHYSICS_TIMESTEP)


def resolve_velocity_limits(
    pure_pursuit_config: Any = None, rotation_config: Any = None
) -> Tuple[float, float]:
    """The linear/angular caps a saturated recording tick actually hits.

    ``pure_pursuit_config``/``rotation_config`` are whatever the caller is
    about to hand ``replay.record_segmented_demo``; ``None`` means "that
    function's own defaults", which is the pipeline's normal path.

    The angular cap is the *tightest* of the two things that bound it, since
    both replay phases record into the same corpus: the ``max_vw`` the move
    phase passes down, and the look phase's own ``w_max``.
    """
    v_max = DEFAULT_V_MAX_MPS
    if pure_pursuit_config is not None and getattr(pure_pursuit_config, "v_max", None):
        v_max = float(pure_pursuit_config.v_max)

    if rotation_config is not None:
        look_w_max = float(rotation_config.w_max)
    else:
        from continuous_demos.controllers import HeadingRotationConfig

        look_w_max = float(HeadingRotationConfig().w_max)

    return float(v_max), float(min(REPLAY_MOVE_MAX_VW_RADPS, look_w_max))


@functools.lru_cache(maxsize=1)
def current_code_commit() -> Optional[str]:
    """Short git hash of this checkout, or ``None`` outside a git tree."""
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=str(Path(__file__).resolve().parent),
            capture_output=True,
            text=True,
            timeout=10,
            check=True,
        )
        return out.stdout.strip() or None
    except Exception:
        return None


def params_for_generation(
    native_fps: float,
    robot_sim: Any = None,
    *,
    image_width: Optional[int] = None,
    image_height: Optional[int] = None,
    image_ext: Optional[str] = None,
    goal_threshold_m: Optional[float] = None,
    urdf: Optional[str] = None,
    generator: Optional[str] = None,
    pure_pursuit_config: Any = None,
    rotation_config: Any = None,
    physics_timestep: Optional[float] = None,
) -> RecordingParams:
    """Assemble the block a generator stamps onto every record it writes."""
    if native_fps <= 0:
        raise ValueError(f"native_fps must be positive, got {native_fps}")
    dt_native = 1.0 / float(native_fps)
    step = float(physics_timestep) if physics_timestep else probe_physics_timestep(robot_sim)
    steps_per_tick = dt_native / step
    v_max, w_max = resolve_velocity_limits(pure_pursuit_config, rotation_config)
    return RecordingParams(
        native_fps=float(native_fps),
        dt_native=dt_native,
        physics_timestep=step,
        physics_steps_per_tick=steps_per_tick,
        on_physics_grid=abs(steps_per_tick - round(steps_per_tick)) < 1e-6,
        v_max_mps=v_max,
        w_max_radps=w_max,
        image_width=int(image_width) if image_width is not None else None,
        image_height=int(image_height) if image_height is not None else None,
        image_ext=image_ext,
        goal_threshold_m=float(goal_threshold_m) if goal_threshold_m is not None else None,
        urdf=Path(urdf).name if urdf else None,
        generator=generator,
        code_commit=current_code_commit(),
        schema_version=SCHEMA_VERSION,
    )


def legacy_params(native_fps: float, note: str = "assumed by the caller") -> RecordingParams:
    """Parameters for a pre-schema corpus, from an explicitly supplied rate.

    ``schema_version`` is 0 and ``assumed_note`` is set, so anything that
    prints or re-stamps these values makes it obvious they were asserted by a
    human rather than read off the data. The physics timestep and the velocity
    caps are the ones this stack has always had; only the *rate* was ever in
    question, and that is the argument.
    """
    dt_native = 1.0 / float(native_fps)
    steps_per_tick = dt_native / DEFAULT_PHYSICS_TIMESTEP
    return RecordingParams(
        native_fps=float(native_fps),
        dt_native=dt_native,
        physics_timestep=DEFAULT_PHYSICS_TIMESTEP,
        physics_steps_per_tick=steps_per_tick,
        on_physics_grid=abs(steps_per_tick - round(steps_per_tick)) < 1e-6,
        v_max_mps=DEFAULT_V_MAX_MPS,
        w_max_radps=REPLAY_MOVE_MAX_VW_RADPS,
        generator=None,
        code_commit=None,
        schema_version=0,
        assumed_note=note,
    )


# ---------------------------------------------------------------------------
# Reading it back
# ---------------------------------------------------------------------------
def params_from_record(record: Dict[str, Any]) -> Optional[RecordingParams]:
    """The parameter block of one JSONL record, or ``None`` if it predates the schema."""
    blob = record.get(RECORDING_KEY)
    if not isinstance(blob, dict):
        return None
    return RecordingParams.from_dict(blob)


def _first_record(path: Path) -> Optional[Dict[str, Any]]:
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                return json.loads(line)
            except json.JSONDecodeError:
                continue
    return None


@dataclass
class ResolvedRecording:
    """Outcome of :func:`resolve_corpus_params`."""

    params: RecordingParams
    #: ``"metadata"`` (read off the corpus) or ``"assumed"`` (caller-supplied).
    source: str
    shards_with: List[str] = field(default_factory=list)
    shards_without: List[str] = field(default_factory=list)

    @property
    def from_metadata(self) -> bool:
        return self.source == "metadata"

    def banner(self) -> str:
        if self.from_metadata:
            return f"Recording params (read from metadata): {self.params.describe()}"
        return (
            f"Recording params (ASSUMED -- corpus predates the schema): "
            f"{self.params.describe()}"
        )


def _shard_paths(metadata_dir: Path) -> List[Path]:
    return sorted(Path(metadata_dir).glob("*.jsonl"))


def resolve_corpus_params(
    metadata_dir: Path,
    assumed_native_fps: Optional[float] = None,
    *,
    shard_paths: Optional[Sequence[Path]] = None,
    flag_name: str = "--native-fps",
) -> ResolvedRecording:
    """Establish, once, how a corpus was recorded. See the module docstring.

    ``assumed_native_fps`` is the consumer's ``--native-fps`` (``flag_name``
    names it in error messages, since not every consumer spells it that way).
    It is *only* a fallback for a corpus that does not record its own rate; if
    the corpus does record one and the two disagree, that is an error rather
    than an override.
    """
    paths = list(shard_paths) if shard_paths is not None else _shard_paths(Path(metadata_dir))
    if not paths:
        raise RecordingParamsError(f"No *.jsonl shards found under {metadata_dir}")

    with_params: List[Tuple[Path, RecordingParams]] = []
    without: List[Path] = []
    for path in paths:
        record = _first_record(path)
        if record is None:
            continue  # empty shard tells us nothing either way
        params = params_from_record(record)
        if params is None:
            without.append(path)
        else:
            with_params.append((path, params))

    if with_params and without:
        raise InconsistentRecordingParams(
            f"{len(with_params)} shard(s) under {metadata_dir} record their parameters "
            f"and {len(without)} do not (e.g. {without[0].name}). This corpus mixes "
            "pre- and post-schema generations, which almost certainly means it mixes "
            "recording rates too. Split it and build the halves separately."
        )

    if with_params:
        head_path, head = with_params[0]
        for path, params in with_params[1:]:
            if not params.agrees_with(head):
                raise InconsistentRecordingParams(
                    f"Shards disagree about how they were recorded: {head_path.name} has "
                    f"{head.consistency_view()} but {path.name} has "
                    f"{params.consistency_view()}. Do not build across them."
                )
        if assumed_native_fps is not None and abs(float(assumed_native_fps) - head.native_fps) > _FLOAT_TOL:
            raise InconsistentRecordingParams(
                f"{flag_name} {assumed_native_fps:g} was passed, but this corpus records "
                f"native_fps={head.native_fps:g} (schema_version={head.schema_version}). "
                "The recorded value is authoritative; drop the flag. If you genuinely "
                "believe the recorded value is wrong, fix the corpus rather than "
                "overriding it here."
            )
        return ResolvedRecording(
            params=head,
            source="metadata",
            shards_with=[p.name for p, _ in with_params],
        )

    if assumed_native_fps is None:
        raise MissingRecordingParams(
            f"No shard under {metadata_dir} records its recording parameters "
            f"(no '{RECORDING_KEY}' key), so this corpus predates schema_version "
            f"{SCHEMA_VERSION} and its frame rate is not stored anywhere. Refusing to "
            f"guess. Every pre-schema corpus in this repo was recorded at "
            f"{LEGACY_NATIVE_FPS:g} Hz -- pass {flag_name} {LEGACY_NATIVE_FPS:g} to say so "
            "explicitly, or regenerate with the current generator, which records it."
        )

    return ResolvedRecording(
        params=legacy_params(
            assumed_native_fps, note=f"assumed via --native-fps {float(assumed_native_fps):g}"
        ),
        source="assumed",
        shards_without=[p.name for p in without],
    )


def check_record_consistency(
    record: Dict[str, Any], resolved: ResolvedRecording, where: str = ""
) -> None:
    """Per-record guard, cheap enough to run inside a build loop.

    Catches the case :func:`resolve_corpus_params` cannot see from first lines
    alone: a shard that was *appended to* by a later run at a different rate,
    so its first record is honest and its last one isn't.
    """
    params = params_from_record(record)
    if params is None:
        if resolved.from_metadata:
            raise InconsistentRecordingParams(
                f"{where or 'a record'} carries no '{RECORDING_KEY}' block, but the rest of "
                "this corpus does -- the shard was appended to across the schema change."
            )
        return
    if not resolved.from_metadata:
        raise InconsistentRecordingParams(
            f"{where or 'a record'} records its own parameters ({params.consistency_view()}), "
            "but the corpus was resolved from a caller-supplied --native-fps. The shard was "
            "appended to across the schema change."
        )
    if not params.agrees_with(resolved.params):
        raise InconsistentRecordingParams(
            f"{where or 'a record'} was recorded with {params.consistency_view()}, but the "
            f"corpus resolved to {resolved.params.consistency_view()}. The shard mixes two "
            "generations; do not build across it."
        )


def shard_params(path: Path) -> Optional[RecordingParams]:
    """Parameters of an individual shard's first record (``None`` if pre-schema)."""
    record = _first_record(Path(path))
    return params_from_record(record) if record else None


def iter_shard_params(metadata_dir: Path) -> Iterable[Tuple[Path, Optional[RecordingParams]]]:
    for path in _shard_paths(Path(metadata_dir)):
        yield path, shard_params(path)


def format_grid_note(params: RecordingParams) -> str:
    """One-line human note about whether the rate sits on the physics grid."""
    n = params.physics_steps_per_tick
    if params.on_physics_grid:
        return (
            f"{params.native_fps:g} Hz -> dt={params.dt_native:.4g}s = exactly "
            f"{round(n)} x {params.physics_timestep:g}s physics steps (uniform motion)."
        )
    lo, hi = math.floor(n), math.ceil(n)
    ripple = 100.0 * (hi - lo) / n
    return (
        f"{params.native_fps:g} Hz -> dt={params.dt_native:.4g}s = {n:.4g} x "
        f"{params.physics_timestep:g}s physics steps: OFF-GRID, physics time per tick "
        f"alternates between {lo * params.physics_timestep:.3g}s and "
        f"{hi * params.physics_timestep:.3g}s, a {ripple:.0f}% per-tick velocity ripple."
    )
