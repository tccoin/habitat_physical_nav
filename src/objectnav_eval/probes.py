"""Diagnostics that ride along with a rollout.

A :class:`RolloutProbe` sees every control tick and every chunk boundary and
produces a dict at the end of the episode, which lands in that episode's result
record and is aggregated across episodes. It is the extension point for
questions about *how* the robot moved, as opposed to whether it succeeded --
task metrics belong in the task layer as habitat ``Measure`` subclasses instead.

Probes must not touch the simulator: they see only what the executor hands them,
so they cost nothing and cannot perturb a run.

The tracking diagnostic
-----------------------
The training demonstrations were generated by a DWPP path controller, but
evaluation executes the policy's chunks through a PID pose controller. If the
PID cannot keep up, closed-loop numbers understate the policy and we are
measuring the executor rather than the model.

The evidence that prompted this: correcting the control timestep from 1/30 to
the true 1/20 dropped per-step displacement from 0.0696 to 0.0404 m/step -- a
42% fall for only a 33% reduction in time per step. That is the signature of a
tracker undershooting when asked to execute at true demonstration speed.

:class:`TrackingDiagnostic` measures it directly: for every tick, what
displacement was commanded, what was achieved, and how far behind the robot
ended up. It is a **diagnostic, not a gate** -- oracle replay accumulates PID
error over a whole trajectory and would understate the loop regardless, so the
number is here to be read, not to block anything.

The behavioural probes
----------------------
Success, SPL and distance say whether the robot got there. They say nothing
about *how it looked getting there*, and the failure modes that distinguish
policy heads live there: one head creeps forward without committing, the next
moves confidently but wiggles, crashes and freezes. Both can score the same
SPL. :class:`MotionTaxonomy`, :class:`CollisionProbe` and
:class:`MotionCoherence` make those three observations -- frozen time,
obstruction, and incoherent motion -- into numbers, so "it looks drunk in the
video" becomes a quantity that is comparable across every head that runs
through this suite.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

import numpy as np

from objectnav_eval.executor import ChunkExecution, ContactSnapshot, TickRecord

# Below this, a commanded displacement is noise and the ratio is meaningless.
_MOVING_EPS_M = 1e-3
_MOVING_EPS_RAD = math.radians(0.5)


def _wrap(angle: float) -> float:
    return (angle + math.pi) % (2 * math.pi) - math.pi


class RolloutProbe:
    """Interface for a per-episode diagnostic."""

    name: str = "probe"

    def reset(self, episode: Any) -> None:  # pragma: no cover - interface
        raise NotImplementedError

    def on_tick(self, record: TickRecord) -> None:
        pass

    def on_chunk(self, execution: ChunkExecution) -> None:
        pass

    def summary(self) -> Dict[str, Any]:  # pragma: no cover - interface
        raise NotImplementedError


@dataclass
class TrackingDiagnostic(RolloutProbe):
    """Commanded vs achieved displacement, tracking lag, undershoot ratio."""

    name: str = "tracking"
    #: Keep the per-tick series in the episode record. Off by default: a
    #: 200-step episode is 1000 ticks, and the summary statistics answer the
    #: question. Useful when chasing a specific episode.
    keep_series: bool = False

    commanded: List[float] = field(default_factory=list)
    achieved: List[float] = field(default_factory=list)
    lag: List[float] = field(default_factory=list)
    commanded_yaw: List[float] = field(default_factory=list)
    achieved_yaw: List[float] = field(default_factory=list)
    yaw_lag: List[float] = field(default_factory=list)
    chunk_end_lag: List[float] = field(default_factory=list)
    chunk_commanded_net: List[float] = field(default_factory=list)
    chunk_achieved_net: List[float] = field(default_factory=list)
    saturation: Dict[str, int] = field(default_factory=dict)

    def reset(self, episode: Any = None) -> None:
        self.commanded, self.achieved, self.lag = [], [], []
        self.commanded_yaw, self.achieved_yaw, self.yaw_lag = [], [], []
        self.chunk_end_lag = []
        self.chunk_commanded_net, self.chunk_achieved_net = [], []
        self.saturation = {}

    def on_tick(self, record: TickRecord) -> None:
        self.commanded.append(record.commanded_displacement)
        self.achieved.append(record.achieved_displacement)
        self.lag.append(record.lag)
        self.commanded_yaw.append(
            abs(_wrap(float(record.setpoint[2]) - float(record.previous_setpoint[2])))
        )
        self.achieved_yaw.append(
            abs(_wrap(float(record.pose[2]) - float(record.previous_pose[2])))
        )
        self.yaw_lag.append(
            abs(_wrap(float(record.pose[2]) - float(record.setpoint[2])))
        )
        for key, value in record.saturation.items():
            self.saturation[key] = self.saturation.get(key, 0) + int(value)

    def on_chunk(self, execution: ChunkExecution) -> None:
        self.chunk_end_lag.append(execution.end_lag)
        if len(execution.setpoints):
            self.chunk_commanded_net.append(
                float(np.linalg.norm(execution.setpoints[-1][:2] - execution.anchor[:2]))
            )
            self.chunk_achieved_net.append(
                float(np.linalg.norm(execution.poses[-1][:2] - execution.anchor[:2]))
            )

    def summary(self) -> Dict[str, Any]:
        commanded = np.asarray(self.commanded, dtype=float)
        achieved = np.asarray(self.achieved, dtype=float)
        if commanded.size == 0:
            return {"ticks": 0}

        moving = commanded > _MOVING_EPS_M
        yaw_commanded = np.asarray(self.commanded_yaw, dtype=float)
        yaw_achieved = np.asarray(self.achieved_yaw, dtype=float)
        yaw_moving = yaw_commanded > _MOVING_EPS_RAD

        out: Dict[str, Any] = {
            "ticks": int(commanded.size),
            "moving_ticks": int(moving.sum()),
            "commanded_disp_mean_m": float(commanded.mean()),
            "achieved_disp_mean_m": float(achieved.mean()),
            # Ratio of sums, not mean of ratios: a tick that commands nothing
            # would otherwise contribute a 0/0 or an enormous ratio.
            "undershoot_ratio": _ratio(achieved.sum(), commanded.sum()),
            "tracking_lag_mean_m": float(np.mean(self.lag)),
            "tracking_lag_p95_m": float(np.percentile(self.lag, 95)),
            "tracking_lag_max_m": float(np.max(self.lag)),
            "yaw_commanded_mean_deg": float(np.degrees(yaw_commanded.mean())),
            "yaw_achieved_mean_deg": float(np.degrees(yaw_achieved.mean())),
            "yaw_undershoot_ratio": _ratio(yaw_achieved.sum(), yaw_commanded.sum()),
            "yaw_lag_mean_deg": float(np.degrees(np.mean(self.yaw_lag))),
        }
        if moving.any():
            out["commanded_disp_mean_moving_m"] = float(commanded[moving].mean())
            out["achieved_disp_mean_moving_m"] = float(achieved[moving].mean())
            out["undershoot_ratio_moving"] = _ratio(
                achieved[moving].sum(), commanded[moving].sum()
            )
            out["undershoot_ratio_median"] = float(
                np.median(achieved[moving] / commanded[moving])
            )
        if yaw_moving.any():
            out["yaw_undershoot_ratio_moving"] = _ratio(
                yaw_achieved[yaw_moving].sum(), yaw_commanded[yaw_moving].sum()
            )
        if self.chunk_end_lag:
            out["chunk_end_lag_mean_m"] = float(np.mean(self.chunk_end_lag))
            out["chunk_end_lag_max_m"] = float(np.max(self.chunk_end_lag))
        if self.chunk_commanded_net:
            out["chunk_commanded_net_mean_m"] = float(np.mean(self.chunk_commanded_net))
            out["chunk_achieved_net_mean_m"] = float(np.mean(self.chunk_achieved_net))
            out["chunk_undershoot_ratio"] = _ratio(
                float(np.sum(self.chunk_achieved_net)),
                float(np.sum(self.chunk_commanded_net)),
            )
        # The controller's own clamps are the mechanism an undershoot would work
        # through, so report how often each one bound.
        for key, count in sorted(self.saturation.items()):
            out[f"saturated_{key}_frac"] = float(count) / float(commanded.size)
        if self.keep_series:
            out["commanded_series_m"] = [round(v, 4) for v in self.commanded]
            out["achieved_series_m"] = [round(v, 4) for v in self.achieved]
            out["lag_series_m"] = [round(v, 4) for v in self.lag]
        return out


def _ratio(numerator: float, denominator: float) -> float:
    if not np.isfinite(denominator) or denominator <= 0:
        return float("nan")
    return float(numerator / denominator)


@dataclass
class GoalDistanceProbe(RolloutProbe):
    """Per-policy-step distance-to-goal trace.

    Kept as a probe rather than a metric because it is a *trace*: the headline
    numbers (final, minimum) come from the task's measures, and this is what you
    plot when one episode looks wrong.
    """

    name: str = "goal_distance"
    trace: List[float] = field(default_factory=list)

    def reset(self, episode: Any = None) -> None:
        self.trace = []

    def observe(self, distance: float) -> None:
        self.trace.append(float(distance))

    def summary(self) -> Dict[str, Any]:
        finite = [v for v in self.trace if np.isfinite(v)]
        return {
            "trace": [round(v, 3) if np.isfinite(v) else None for v in self.trace],
            "min_m": float(min(finite)) if finite else float("inf"),
            "final_m": self.trace[-1] if self.trace else float("nan"),
        }


# ---------------------------------------------------------------------------
# Behavioural probes: what the motion looks like, not whether it succeeded
# ---------------------------------------------------------------------------
#
# The tick taxonomy and its thresholds are *not* new here. They come from
# ``dump/data_diagnostics/croppability/segment_decomposition.py`` via
# ``dump/regen_readiness/tick_decomposition.py``, and are the same ones the
# demonstration corpus is characterised with:
#
#   DRIVE   |dxy| >= XY_T                                    (translating)
#   TURN    |dxy| <  XY_T and |dtheta| >= TH_T               (turning in place)
#   SETTLE  |dxy| <  XY_T and EPS <= |dtheta| < TH_T         (controller ringing)
#   FROZEN  |dxy| <  EPS  and |dtheta| < EPS                 (truly idle)
#
# with ``XY_T = 0.01 m`` and ``TH_T = 0.02 rad`` **per tick at 20 Hz**. Reusing
# them verbatim is the point: eval numbers are then directly comparable to the
# corpus composition table, instead of being a fresh incompatible taxonomy.
#
# But they are per-tick *displacements* at one specific rate, so at face value
# they denote 0.2 m/s at 20 Hz and 0.4 m/s at 10 Hz -- which would silently
# change what "frozen" means the moment ``--dt`` changes. They are therefore
# stored here as **speeds** and multiplied back by the run's ``dt``.
_DRIVE_SPEED_MPS = 0.01 / 0.05  # 0.20 m/s
_TURN_RATE_RADPS = 0.02 / 0.05  # 0.40 rad/s ~ 23 deg/s
# The corpus's EPS is 1e-6 per tick: "the generator wrote the same pose twice".
# A physics rollout never does that -- the base jitters at the solver's noise
# floor -- so FROZEN is expected to be ~0 in eval and the honest stationary
# measure is FROZEN + SETTLE. Both are reported; see the docs.
_EPS_SPEED_MPS = 1e-6 / 0.05
_EPS_RATE_RADPS = 1e-6 / 0.05

#: A rotation smaller than this is not a direction the policy chose, it is
#: numerical drift, and asking which way it pointed is meaningless. A quarter of
#: the TURN threshold: loose enough to include the small deliberate corrections
#: that a wiggling policy is made of, far above the noise floor.
_FLIP_DEADBAND_FRAC = 0.25

DRIVE, TURN, SETTLE, FROZEN = "drive", "turn", "settle", "frozen"
_CLASSES = (DRIVE, TURN, SETTLE, FROZEN)


def classify_tick(translation: float, rotation: float, dt: float) -> str:
    """One tick's motion class, from body-frame |dxy| and |dtheta| over ``dt``."""
    if translation >= _DRIVE_SPEED_MPS * dt:
        return DRIVE
    if rotation >= _TURN_RATE_RADPS * dt:
        return TURN
    if translation < _EPS_SPEED_MPS * dt and rotation < _EPS_RATE_RADPS * dt:
        return FROZEN
    return SETTLE


def _run_lengths(mask: List[bool]) -> List[int]:
    """Lengths of the maximal runs of ``True`` in ``mask``."""
    out: List[int] = []
    start: Optional[int] = None
    for index, value in enumerate(mask):
        if value and start is None:
            start = index
        elif not value and start is not None:
            out.append(index - start)
            start = None
    if start is not None:
        out.append(len(mask) - start)
    return out


@dataclass
class MotionTaxonomy(RolloutProbe):
    """How the robot spent its time: driving, turning in place, settling, frozen.

    Answers "what share of control ticks is the robot effectively not moving",
    and answers it without conflating *frozen* (going nowhere) with *turning in
    place* (going nowhere while acquiring a new view) -- behaviourally opposite
    things that a single "displacement below threshold" test merges, which has
    caused confusion in this project before.

    Everything is computed twice: on the **commanded** setpoints (what the
    policy asked for) and on the **achieved** poses (what the robot did). The
    gap between them is the interesting part -- a tick that commanded DRIVE and
    achieved FROZEN is the robot being blocked, not the policy standing still.

    Free: pure arithmetic on the ``TickRecord`` the executor already emits.
    """

    name: str = "motion"
    dt: float = 0.05

    commanded_class: List[str] = field(default_factory=list)
    achieved_class: List[str] = field(default_factory=list)
    achieved_speed: List[float] = field(default_factory=list)
    achieved_rate: List[float] = field(default_factory=list)
    drive_disp: List[float] = field(default_factory=list)
    commanded_drive_disp: List[float] = field(default_factory=list)

    def reset(self, episode: Any = None) -> None:
        self.commanded_class, self.achieved_class = [], []
        self.achieved_speed, self.achieved_rate = [], []
        self.drive_disp, self.commanded_drive_disp = [], []

    def on_tick(self, record: TickRecord) -> None:
        commanded = record.commanded_body_delta()
        achieved = record.achieved_body_delta()
        commanded_xy = float(math.hypot(commanded[0], commanded[1]))
        achieved_xy = float(math.hypot(achieved[0], achieved[1]))
        self.commanded_class.append(
            classify_tick(commanded_xy, abs(float(commanded[2])), self.dt)
        )
        self.achieved_class.append(
            classify_tick(achieved_xy, abs(float(achieved[2])), self.dt)
        )
        self.achieved_speed.append(achieved_xy / self.dt)
        self.achieved_rate.append(abs(float(achieved[2])) / self.dt)
        # Displacement on ticks classified DRIVE, kept separately from
        # `achieved_speed`. "Metres per moving tick" averages DRIVE and TURN
        # together, and a turning-in-place tick contributes ~0 translation --
        # so that quantity is diluted by however much the policy happens to be
        # turning, which is precisely the confound it would be used to rule out.
        # This one answers "when it does drive, how far does it get".
        if self.achieved_class[-1] == "drive":
            self.drive_disp.append(achieved_xy)
        if self.commanded_class[-1] == "drive":
            self.commanded_drive_disp.append(commanded_xy)

    def summary(self) -> Dict[str, Any]:
        ticks = len(self.achieved_class)
        if ticks == 0:
            return {"ticks": 0}
        out: Dict[str, Any] = {
            "ticks": ticks,
            "dt_s": self.dt,
            "drive_threshold_mps": _DRIVE_SPEED_MPS,
            "turn_threshold_radps": _TURN_RATE_RADPS,
        }
        # Distance covered per DRIVE tick -- the "when it moves, does it move
        # well" number, independent of the drive/turn mix.
        for label, series in (("", self.drive_disp),
                              ("commanded_", self.commanded_drive_disp)):
            if series:
                out[f"{label}drive_disp_mean_m"] = float(np.mean(series))
                out[f"{label}drive_disp_median_m"] = float(np.median(series))
                out[f"{label}drive_speed_mean_mps"] = float(np.mean(series)) / self.dt
            else:
                out[f"{label}drive_disp_mean_m"] = 0.0
                out[f"{label}drive_disp_median_m"] = 0.0
                out[f"{label}drive_speed_mean_mps"] = 0.0
        # Metres of translation per unit of *time spent driving* -- what an
        # efficiency comparison wants when two policies turn different amounts.
        out["drive_distance_m"] = float(np.sum(self.drive_disp))
        for label, classes in (("", self.achieved_class),
                               ("commanded_", self.commanded_class)):
            for name in _CLASSES:
                out[f"{label}frac_{name}"] = classes.count(name) / ticks
            # The headline "not moving" number: neither translating nor
            # rotating enough to count as either. Identical by construction to
            # ``frac_stationary`` in analyze_chunk_motion.py, so it can be read
            # straight against the corpus.
            out[f"{label}frac_stationary"] = (
                classes.count(SETTLE) + classes.count(FROZEN)
            ) / ticks
        stationary = [c in (SETTLE, FROZEN) for c in self.achieved_class]
        runs = _run_lengths(stationary)
        if runs:
            out["stationary_runs"] = len(runs)
            out["stationary_run_median_ticks"] = float(np.median(runs))
            out["stationary_run_max_ticks"] = int(max(runs))
            out["stationary_run_max_s"] = float(max(runs) * self.dt)
            # Is the stillness spread thinly (a slightly slow policy) or lumped
            # into long stalls (the "significant frozen time" the videos show)?
            out["stationary_share_in_runs_ge_10"] = float(
                sum(r for r in runs if r >= 10) / max(1, sum(runs))
            )
        # Commanded a real move and did not get one: the blocked-motion signal
        # the tracking diagnostic's undershoot cannot separate from PID lag.
        commanded_drive = [c == DRIVE for c in self.commanded_class]
        n_commanded_drive = sum(commanded_drive)
        if n_commanded_drive:
            out["commanded_drive_ticks"] = n_commanded_drive
            out["blocked_drive_frac"] = sum(
                1
                for commanded, achieved in zip(self.commanded_class, self.achieved_class)
                if commanded == DRIVE and achieved != DRIVE
            ) / n_commanded_drive
        out["median_speed_mps"] = float(np.median(self.achieved_speed))
        out["p90_speed_mps"] = float(np.percentile(self.achieved_speed, 90))
        out["median_turnrate_degps"] = float(np.degrees(np.median(self.achieved_rate)))
        return out


@dataclass
class CollisionProbe(RolloutProbe):
    """How often the robot is jammed against scene geometry while trying to drive.

    The trap this is built around: **the robot is always in contact with the
    floor**, so a contact count is not a collision measure.
    ``executor.robot_contacts`` splits ground from obstruction on the contact
    normal before this ever sees it, and a healthy episode still has a non-zero
    ground count (~2 contact points; see
    ``dump/drive_failure_detection/FINDINGS.md``).

    That findings document *rejected* contact-based signals for escape
    detection, because that had to be bulletproof enough to accept or reject
    episodes. This is a descriptive diagnostic that gates nothing, so a
    reasonable contact measure is the right tool -- with its limits stated:
    an instantaneous end-of-tick sample, a 45-degree normal split that
    misreads steep ramps, and no notion of how hard the robot is pushing
    beyond the peak normal force.

    Inert unless the executor was built with ``collect_contacts=True``.
    """

    name: str = "contact"
    dt: float = 0.05

    obstructed: List[bool] = field(default_factory=list)
    commanded_drive: List[bool] = field(default_factory=list)
    ground: List[int] = field(default_factory=list)
    obstruction: List[int] = field(default_factory=list)
    peak_force: List[float] = field(default_factory=list)
    distance_m: float = 0.0

    def reset(self, episode: Any = None) -> None:
        self.obstructed, self.commanded_drive = [], []
        self.ground, self.obstruction, self.peak_force = [], [], []
        self.distance_m = 0.0

    def on_tick(self, record: TickRecord) -> None:
        if record.contacts is None:
            return
        commanded = record.commanded_body_delta()
        self.commanded_drive.append(
            classify_tick(
                float(math.hypot(commanded[0], commanded[1])),
                abs(float(commanded[2])),
                self.dt,
            )
            == DRIVE
        )
        self.obstructed.append(record.contacts.obstruction > 0)
        self.ground.append(record.contacts.ground)
        self.obstruction.append(record.contacts.obstruction)
        self.peak_force.append(record.contacts.max_obstruction_force)
        self.distance_m += record.achieved_displacement

    def summary(self) -> Dict[str, Any]:
        ticks = len(self.obstructed)
        if ticks == 0:
            return {"ticks": 0, "enabled": False}
        runs = _run_lengths(self.obstructed)
        out: Dict[str, Any] = {
            "ticks": ticks,
            "enabled": True,
            "mean_ground_contacts": float(np.mean(self.ground)),
            "mean_obstruction_contacts": float(np.mean(self.obstruction)),
            "obstructed_frac": sum(self.obstructed) / ticks,
            # Maximal runs, not ticks: leaning on one wall for 200 ticks is one
            # collision, and counting ticks would make a single stuck episode
            # dominate every aggregate.
            "collisions": len(runs),
            "collisions_per_100_ticks": 100.0 * len(runs) / ticks,
            "longest_obstructed_run_ticks": int(max(runs)) if runs else 0,
            "peak_obstruction_force_max": float(max(self.peak_force)),
            "distance_m": float(self.distance_m),
        }
        if self.distance_m > 1e-6:
            out["collisions_per_m"] = len(runs) / self.distance_m
        driving = sum(self.commanded_drive)
        if driving:
            # The number the question actually asks for: of the ticks where the
            # policy was trying to go somewhere, how many were spent in contact
            # with something other than the floor.
            out["driving_ticks"] = driving
            out["obstructed_while_driving_frac"] = sum(
                1 for o, d in zip(self.obstructed, self.commanded_drive) if o and d
            ) / driving
        return out


@dataclass
class MotionCoherence(RolloutProbe):
    """Is the commanded trajectory a sequence, or a pile of independent samples?

    The bin head models each of its 30 output slots (10 ticks x 3 channels) as
    fully independent. Every individual tick is then plausible while the
    *sequence* need not be: consecutive ticks are uncorrelated, and within a
    tick forward speed and rotation are drawn independently despite being
    strongly anti-correlated in real driving. "Drunken" is what that looks like
    from outside, and these are its two measurable signatures.

    **Rotation sign-flip rate.** Of the adjacent tick pairs where both ticks
    genuinely rotate, how often does the commanded direction reverse. Reported
    *within chunk* as the headline: across a chunk boundary the policy has seen
    a new image and re-anchored, so changing its mind there is legitimate --
    within a chunk it is one forward pass contradicting itself.

    **Rotation directness.** Per chunk, ``|sum dtheta| / sum |dtheta|``. 1.0 is
    a committed turn; near 0 is rotation that cancels itself out and buys no
    heading change.

    **Forward/rotation correlation.** ``corr(|forward|, |dtheta|)`` over ticks.
    Real driving is nearly always in a drive phase or a turn phase, so this is
    negative; independent per-slot sampling drives it towards zero.

    Free: arithmetic on ``TickRecord``s.
    """

    name: str = "coherence"
    dt: float = 0.05

    commanded_rotation: List[float] = field(default_factory=list)
    achieved_rotation: List[float] = field(default_factory=list)
    commanded_forward: List[float] = field(default_factory=list)
    tick_in_chunk: List[int] = field(default_factory=list)
    chunk_directness: List[float] = field(default_factory=list)

    def reset(self, episode: Any = None) -> None:
        self.commanded_rotation, self.achieved_rotation = [], []
        self.commanded_forward = []
        self.tick_in_chunk = []
        self.chunk_directness = []

    def on_tick(self, record: TickRecord) -> None:
        commanded = record.commanded_body_delta()
        self.commanded_rotation.append(float(commanded[2]))
        self.commanded_forward.append(abs(float(commanded[0])))
        self.achieved_rotation.append(float(record.achieved_body_delta()[2]))
        self.tick_in_chunk.append(int(record.tick_in_chunk))

    def on_chunk(self, execution: ChunkExecution) -> None:
        rotations = [
            float(tick.commanded_body_delta()[2]) for tick in execution.ticks
        ]
        total = sum(abs(r) for r in rotations)
        if total > _MOVING_EPS_RAD:
            self.chunk_directness.append(abs(sum(rotations)) / total)

    # ------------------------------------------------------------------
    def _flip_rate(
        self, rotations: List[float], deadband: float, within_chunk: bool
    ) -> Dict[str, Any]:
        pairs = flips = 0
        for index in range(1, len(rotations)):
            if within_chunk and self.tick_in_chunk[index] == 0:
                continue  # a chunk boundary: the policy has re-observed
            before, after = rotations[index - 1], rotations[index]
            if abs(before) < deadband or abs(after) < deadband:
                continue
            pairs += 1
            if before * after < 0:
                flips += 1
        return {"pairs": pairs, "flips": flips,
                "rate": (flips / pairs) if pairs else float("nan")}

    def summary(self) -> Dict[str, Any]:
        ticks = len(self.commanded_rotation)
        if ticks == 0:
            return {"ticks": 0}
        loose = _FLIP_DEADBAND_FRAC * _TURN_RATE_RADPS * self.dt
        strict = _TURN_RATE_RADPS * self.dt
        out: Dict[str, Any] = {
            "ticks": ticks,
            "flip_deadband_radps": _FLIP_DEADBAND_FRAC * _TURN_RATE_RADPS,
        }
        for label, rotations in (("", self.commanded_rotation),
                                 ("achieved_", self.achieved_rotation)):
            for suffix, within in (("within_chunk", True), ("all_adjacent", False)):
                stats = self._flip_rate(rotations, loose, within)
                out[f"{label}flip_rate_{suffix}"] = stats["rate"]
                out[f"{label}flip_pairs_{suffix}"] = stats["pairs"]
        # Same statistic restricted to ticks that clear the full TURN threshold:
        # a stricter read that cannot be inflated by near-deadband jitter.
        strict_stats = self._flip_rate(self.commanded_rotation, strict, True)
        out["flip_rate_within_chunk_turning"] = strict_stats["rate"]
        out["flip_pairs_within_chunk_turning"] = strict_stats["pairs"]
        if self.chunk_directness:
            out["rotation_directness"] = float(np.mean(self.chunk_directness))
            out["rotation_directness_median"] = float(np.median(self.chunk_directness))
        out["forward_rotation_corr"] = _corr(
            self.commanded_forward, [abs(r) for r in self.commanded_rotation]
        )
        out["mean_abs_turnrate_degps"] = float(
            np.degrees(np.mean(np.abs(self.commanded_rotation))) / self.dt
        )
        return out


def _corr(a: List[float], b: List[float]) -> float:
    """Pearson correlation, ``nan`` when either side is constant."""
    if len(a) < 2:
        return float("nan")
    x, y = np.asarray(a, dtype=float), np.asarray(b, dtype=float)
    if not (np.std(x) > 0 and np.std(y) > 0):
        return float("nan")
    return float(np.corrcoef(x, y)[0, 1])


# The robot leaving the world. Thresholds are NOT chosen here -- they are the
# ones the demonstration generator's escape detector was validated at, over
# 2,227 episodes across all 56 scenes: 23/23 true positives, 0 false positives,
# with every run length between 15 and 39 ticks empty (a flat surface, not a
# knife edge). See /Projects/spatial_training/dump/drive_failure_detection/
# FINDINGS.md. Matching them means "escaped" denotes the same event in training
# data and in evaluation, which is the whole point of adding it here.
#
# Two things that document rejected alternatives, so they are not re-tried:
#   * Depth alone is useless -- healthy episodes legitimately drop up to 6.4 m
#     (a stairwell descent at 6.5 m/s), and 8 of 40 episodes in one scene drop
#     over 3 m.
#   * Contact-based detection missed 3 of the 23 escapes and needed floor/wall
#     normal classification. Vertical speed needs neither.
_ESCAPE_SPEED_MPS = 2.0     # sustained descent faster than this...
_ESCAPE_DURATION_S = 1.0    # ...for at least this long


@dataclass
class EscapeProbe(RolloutProbe):
    """Did the robot fall out of the navmesh, and how far.

    Passive: it reads ``TickRecord.height`` (the vertical prismatic joint the
    executor samples) and never touches the simulator. It gates nothing.

    This is a strictly different question from the summary's
    ``episodes_off_navmesh``, which counts episodes whose *final* geodesic is
    non-finite. That conflates three unrelated states: a robot in a nook the
    mesh does not cover, one stranded on a disconnected island, and one that
    fell out of the world entirely. Only the third is a simulator failure rather
    than a navigation outcome, and it is the one every trajectory metric scores
    as healthy -- an escaped robot drives through the void with *better*
    reference tracking than a healthy one.
    """

    name: str = "escape"
    dt: float = 0.05
    heights: List[float] = field(default_factory=list)

    def reset(self, episode: Any) -> None:
        self.heights = []

    def on_tick(self, record: TickRecord) -> None:
        if record.height is not None:
            self.heights.append(float(record.height))

    def summary(self) -> Dict[str, Any]:
        if len(self.heights) < 2:
            return {"escaped": False, "ticks": len(self.heights)}
        h = np.asarray(self.heights, dtype=float)
        # Descent speed is positive downward, so the thresholds read as written.
        descent = -np.diff(h) / self.dt
        fast = descent >= _ESCAPE_SPEED_MPS
        longest = run = 0
        for flag in fast:
            run = run + 1 if flag else 0
            longest = max(longest, run)
        needed = max(1, int(round(_ESCAPE_DURATION_S / self.dt)))
        return {
            "escaped": bool(longest >= needed),
            "peak_descent_mps": float(descent.max()),
            "longest_descent_ticks": int(longest),
            "longest_descent_s": float(longest * self.dt),
            "total_drop_m": float(h[0] - h.min()),
            "net_height_change_m": float(h[-1] - h[0]),
            "escape_threshold_mps": _ESCAPE_SPEED_MPS,
            "escape_threshold_ticks": needed,
            "ticks": len(h),
        }


@dataclass
class TrajectoryLog(RolloutProbe):
    """The raw trajectory: every control tick's pose, and every chunk commanded.

    Everything else in this module is a *summary*. This is the thing summaries
    are computed from, kept so that a question nobody anticipated can still be
    answered from a finished run instead of requiring a re-run. That has already
    cost this project real time: "did it approach directly or circle", "where
    exactly did it stall", "what was it commanding when it left the navmesh" were
    all answered from video and aggregates because the trajectory was discarded.

    It is nearly free. A 350-step episode is 1750 ticks: the tick series is
    1750 x 4 floats and the chunk series 350 x 10 x 3, about 125 kB per episode
    rounded, against the ~700 kB of MP4 the same episode already writes. Storing
    the cheap thing and keeping the expensive one was the wrong trade.

    Deliberately NOT here: activations and raw frames. Those are large, and the
    video already carries what the frames would show.
    """

    name: str = "trajectory"
    #: Round-trip precision. Millimetre / milliradian is far below the
    #: controller's own tracking error (lag p95 is ~16 mm), so this loses
    #: nothing measurable and roughly halves the stored size.
    ndigits: int = 4
    enabled: bool = True

    ticks: List[List[float]] = field(default_factory=list)
    tick_chunk_index: List[int] = field(default_factory=list)
    tick_in_chunk: List[int] = field(default_factory=list)
    chunks: List[List[List[float]]] = field(default_factory=list)
    chunk_anchor_pose: List[List[float]] = field(default_factory=list)
    chunk_execution_sim_s: List[float] = field(default_factory=list)
    chunk_target_reached: List[Optional[bool]] = field(default_factory=list)
    heights: List[float] = field(default_factory=list)
    cameras: List[Any] = field(default_factory=list)

    def reset(self, episode: Any = None) -> None:
        self.ticks, self.tick_chunk_index, self.tick_in_chunk = [], [], []
        self.chunks, self.chunk_anchor_pose = [], []
        self.chunk_execution_sim_s, self.chunk_target_reached = [], []
        self.heights = []
        self.cameras = []

    def on_tick(self, record: TickRecord) -> None:
        if not self.enabled:
            return
        n = self.ndigits
        # [sim_time, X, Y, theta] in the planar control frame, plus the vertical
        # joint separately -- `pose` is planar by definition, and height is what
        # distinguishes "descending through the floor" from "driving".
        self.ticks.append([
            round(float(record.sim_time), 3),
            round(float(record.pose[0]), n),
            round(float(record.pose[1]), n),
            round(float(record.pose[2]), n),
        ])
        self.tick_chunk_index.append(int(record.chunk_index))
        self.tick_in_chunk.append(int(record.tick_in_chunk))
        height = getattr(record, "height", None)
        self.heights.append(None if height is None else round(float(height), n))
        camera = getattr(record, "camera", None)
        self.cameras.append(None if camera is None else [round(float(v), n) for v in camera])

    def on_chunk(self, execution: ChunkExecution) -> None:
        if not self.enabled:
            return
        chunk = getattr(execution, "chunk", None)
        poses = getattr(chunk, "poses", None) if chunk is not None else None
        if poses is None:
            return
        n = self.ndigits
        self.chunks.append([[round(float(v), n) for v in row] for row in poses])
        self.chunk_anchor_pose.append(
            [round(float(v), n) for v in execution.anchor]
        )
        self.chunk_execution_sim_s.append(float(execution.action_sim_time))
        self.chunk_target_reached.append(execution.action_target_reached)

    def summary(self) -> Dict[str, Any]:
        if not self.enabled or not self.ticks:
            return {"enabled": self.enabled, "ticks": 0}
        out: Dict[str, Any] = {
            "enabled": True,
            "ticks": len(self.ticks),
            #: [sim_time, X, Y, theta] per control tick, planar control frame
            #: (X = habitat_x, Y = -habitat_z, theta CCW from +X).
            "tick_pose": self.ticks,
            "tick_chunk_index": self.tick_chunk_index,
            "tick_in_chunk": self.tick_in_chunk,
            #: Chunks as EMITTED -- (T, 3) relative [dx, dy, dtheta] in the
            #: emitting pose's own frame, before the executor truncated to `gap`.
            "chunks": self.chunks,
            "chunk_anchor_pose": self.chunk_anchor_pose,
            "chunk_execution_sim_s": self.chunk_execution_sim_s,
            "chunk_target_reached": self.chunk_target_reached,
        }
        if any(h is not None for h in self.heights):
            out["tick_height"] = self.heights
        if any(c is not None for c in self.cameras):
            #: Habitat WORLD pose of the camera per tick,
            #: [x, y, z, qw, qx, qy, qz] -- where the rendered frame was taken
            #: from. Carries the mounting offset (~1.19 m up, 0.10 m back) and
            #: the camera pitch, neither of which is in `tick_pose`.
            out["tick_camera"] = self.cameras
        return out


def default_probes(
    keep_series: bool = False, dt: float = 0.05, collect_contacts: bool = False,
    log_trajectory: bool = True,
) -> List[RolloutProbe]:
    """The diagnostics every episode carries.

    The motion taxonomy and the coherence probe are on unconditionally: both are
    a few floating-point operations per tick on data the executor already
    produced, and measured against a rollout they are indistinguishable from
    zero (see docs/OBJECTNAV_EVAL.md). The collision probe is the one that costs
    simulator time, and it is gated on ``collect_contacts``.
    """
    return [
        TrackingDiagnostic(keep_series=keep_series),
        MotionTaxonomy(dt=dt),
        TrajectoryLog(enabled=log_trajectory),
        CollisionProbe(dt=dt),
        MotionCoherence(dt=dt),
        EscapeProbe(dt=dt),
    ]
